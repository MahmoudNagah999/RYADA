<?php

namespace App\Domain\Club\Actions;

use App\Domain\Audit\Actions\RecordActivityAction;
use App\Domain\Audit\Enums\ActivityEvent;
use App\Domain\Club\Models\Club;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;

class UpdateClubLogoAction
{
    public function __construct(private readonly RecordActivityAction $recordActivity) {}

    public function execute(Club $club, UploadedFile $file): Club
    {
        $disk = Storage::disk(config('filesystems.club_logo_disk'));
        $oldPath = $club->logo_path;

        // The file name is generated by Laravel (hash), never taken from the client.
        $newPath = $disk->putFile("clubs/{$club->id}/logo", $file);

        if ($newPath === false) {
            // Rare: disk failure. Let the exception handler return server.error.
            throw new \RuntimeException('Could not store the club logo.');
        }

        try {
            DB::transaction(function () use ($club, $newPath) {
                $club->logo_path = $newPath;
                $club->save();

                $this->recordActivity->execute(
                    event: ActivityEvent::ClubLogoUpdated,
                    subject: $club,
                    properties: [],
                );
            });
        } catch (\Throwable $e) {
            // DB failed: do not leave an orphan file behind.
            $disk->delete($newPath);

            throw $e;
        }

        // Delete the old file only after the DB points to the new one.
        if ($oldPath !== null) {
            $disk->delete($oldPath);
        }

        return $club;
    }
}
